"""Fixed R1 edge profiles; configuration data never becomes Nginx syntax.

One direct edge is the only trusted proxy. Production has one canonical HTTPS
origin. Native authentication/authorization and CSRF remain Odoo's concern.
"""
import argparse
import configparser
from pathlib import Path
import re
from urllib.parse import urlsplit


def production_origin(value):
    if not isinstance(value,str) or not re.fullmatch(r'https://[a-z0-9.-]+(?::[1-9][0-9]{0,4})?',value):
        raise ValueError('One canonical lowercase HTTPS origin is required')
    parsed=urlsplit(value)
    try:port=parsed.port
    except ValueError:raise ValueError('Invalid HTTPS origin port') from None
    host=parsed.hostname or ''
    labels=host.split('.')
    if (not host or len(host)>253 or any(not re.fullmatch(r'[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?',label) for label in labels)
            or port==443 or port is not None and not 1<=port<=65535):
        raise ValueError('Canonical DNS host and optional nondefault HTTPS port required')
    return value,parsed.netloc


def render(mode,origin=None):
    if mode not in ('development','production'):raise ValueError('Explicit development or production profile required')
    if mode=='production':canonical,authority=production_origin(origin)
    elif origin is not None:raise ValueError('Development uses the fixed loopback host policy')
    production=mode=='production'
    hosts=('    "'+authority+'" 1;\n') if production else '''    localhost 1;
    127.0.0.1 1;
    "[::1]" 1;
    "~^(?:[a-z0-9](?:[a-z0-9-]*[a-z0-9])?\\.)+localhost$" 1;
'''
    # $host omits the external port in development. Production pins the entire
    # authority, preventing a forged port from entering redirects/origin checks.
    text='# Generated by tools/http_profile.py; mode='+mode+'\n'
    text+='map '+('$http_host' if production else '$host')+' $mp_host_ok {\n    default 0;\n'+hosts+'}\n'
    if production:text+='map $host $mp_redirect_host_ok { default 0; "'+urlsplit(canonical).hostname+'" 1; }\n'
    text+='''map "$http_origin|$scheme://$http_host" $mp_origin_ok {
    default 0;
    "~^\\|" 1;
    "~*^(https?://[^|/]+)\\|\\1$" 1;
}
map $http_upgrade $mp_connection_upgrade { default upgrade; '' close; }
map $request_id $mp_request_uuid {
    "~^(?<mp_id1>[0-9a-f]{8})(?<mp_id2>[0-9a-f]{4})(?<mp_id3>[0-9a-f]{4})(?<mp_id4>[0-9a-f]{4})(?<mp_id5>[0-9a-f]{12})$" "$mp_id1-$mp_id2-$mp_id3-$mp_id4-$mp_id5";
}
map $uri $mp_rate_error_body {
    default '{"jsonrpc":"2.0","id":null,"error":{"code":429,"message":"Too many requests; try again shortly","data":{"name":"odoo.exceptions.UserError","message":"Too many requests; try again shortly","request_id":"$mp_request_uuid"}}}';
    "~^/api/v1/" '{"error":{"code":"RATE_LIMITED","message":"Too many requests; try again shortly","request_id":"$mp_request_uuid","retryable":true,"details":{"outcome":"not_started"}}}';
}
log_format mp_safe '$remote_addr $request_method $uri $status $body_bytes_sent';
limit_req_zone $binary_remote_addr zone=mp_public:10m rate=50r/s;
limit_req_zone $binary_remote_addr zone=mp_service:10m rate=20r/s;
limit_req_zone $binary_remote_addr zone=mp_operator:10m rate=5r/s;
'''
    text+='limit_req_zone $binary_remote_addr zone=mp_login:10m rate='+('5r/m' if production else '10r/s')+';\n'
    if production:
        text+='''map $arg_debug $mp_debug_blocked { default 1; '' 0; }
server {
    listen 8069;
    server_name _;
    if ($mp_redirect_host_ok = 0) { return 421; }
    if ($request_method !~ ^(?:GET|HEAD)$) { return 403; }
    access_log /dev/stdout mp_safe;
    error_log /dev/stderr crit;
'''
        text+='    return 308 '+canonical+'$request_uri;\n}\n'
    text+='server {\n    listen '+('8443 ssl' if production else '8069')+';\n    server_name _;\n'
    text+='''    if ($mp_host_ok = 0) { return 421; }
    if ($mp_origin_ok = 0) { return 403; }
    server_tokens off;
    client_max_body_size 10m;
    client_header_timeout 15s;
    client_body_timeout 30s;
    keepalive_timeout 30s;
    access_log /dev/stdout mp_safe;
    error_log /dev/stderr crit;
    limit_req_status 429;
    error_page 429 = @mp_rate_limited;
    limit_req zone=mp_public burst=100 nodelay;
    add_header X-Content-Type-Options nosniff always;
    add_header Referrer-Policy same-origin always;
'''
    if production:
        text+='''    ssl_certificate /etc/mp-tls/server.crt;
    ssl_certificate_key /etc/mp-tls/server.key;
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_session_tickets off;
    if ($mp_debug_blocked) { return 403; }
    add_header Strict-Transport-Security "max-age=31536000" always;
    location ~ ^/(?:web/(?:tests|qunit|tour|assets/debug)(?:/|$)|_tests(?:/|$)) { return 403; }
'''
    # Native sessions remain host-only. Nginx tightens flags after Odoo saves
    # the session, without replacing its token, expiry or invalidation semantics.
    common='''        proxy_http_version 1.1;
        proxy_set_header Host $http_host;
        proxy_set_header X-Forwarded-Host $http_host;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header X-Forwarded-Port "";
        proxy_set_header X-Forwarded-Prefix "";
        proxy_set_header X-Real-IP "";
        proxy_set_header Forwarded "";
        proxy_connect_timeout 5s;
        proxy_read_timeout 120s;
'''
    common+='        proxy_cookie_flags session_id httponly samesite=lax '+('secure' if production else 'nosecure')+';\n'
    def location(selector,extra='',port=8069):
        return '    location '+selector+' {\n'+extra+common+'        proxy_pass http://app:'+str(port)+';\n    }\n'
    text+='    location ^~ /web/database { return 403; }\n'
    text+='''    location @mp_rate_limited {
        default_type application/json;
        add_header Retry-After 12 always;
        add_header Cache-Control no-store always;
        add_header X-Content-Type-Options nosniff always;
        add_header Referrer-Policy same-origin always;
'''
    if production:text+='        add_header Strict-Transport-Security "max-age=31536000" always;\n'
    text+='''
        return 429 $mp_rate_error_body;
    }
'''
    text+=location('= /api/v1/operations/validate-upload','        client_max_body_size 100m;\n        proxy_request_buffering off;\n        limit_req zone=mp_operator burst=10 nodelay;\n')
    text+=location('~ ^/web/(?:login|session/authenticate)$','        limit_req zone=mp_login burst='+('10' if production else '30')+' nodelay;\n')
    text+=location('~ ^/api/v1/operations/(?:prepare|request)$','        limit_req zone=mp_operator burst=10 nodelay;\n')
    text+=location('^~ /api/v1/services/','        limit_req zone=mp_service burst=40 nodelay;\n')
    text+=location('/websocket','        proxy_set_header Upgrade $http_upgrade;\n        proxy_set_header Connection $mp_connection_upgrade;\n',port=8072)
    text+=location('/')+'}\n'
    return text


def validate_production_config(path):
    config=configparser.ConfigParser();config.read(path,encoding='utf8')
    if 'options' not in config:raise ValueError('Native configuration required')
    options=config['options'];database=options.get('db_name','')
    handlers=set(part.strip() for part in options.get('log_handler','').split(','))
    if (not options.getboolean('proxy_mode',fallback=False) or options.getboolean('list_db',fallback=True)
            or not re.fullmatch('[a-z][a-z0-9_]{0,62}',database) or options.get('dbfilter')!='^'+database+'$'
            or options.get('dev_mode','').strip() or options.getboolean('test_enable',fallback=False)
            or not handlers&{'werkzeug:ERROR','werkzeug:CRITICAL'}):
        raise ValueError('Production needs one fixed DB, listing/dev/tests disabled and only its direct trusted edge')
    return {'database':database,'proxy_mode':True,'list_db':False,'dev_mode':False,'test_enable':False}


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--mode',choices=['development','production'],required=True);parser.add_argument('--origin');parser.add_argument('--output',type=Path,required=True);parser.add_argument('--odoo-config',type=Path);parser.add_argument('--image');args=parser.parse_args()
    if args.mode=='production':
        if not args.odoo_config:parser.error('Production requires --odoo-config validation before rendering')
        if not args.image or not re.fullmatch('sha256:[0-9a-f]{64}',args.image):parser.error('Production requires --image with the independently approved immutable image ID')
        validate_production_config(args.odoo_config)
    elif args.odoo_config:parser.error('--odoo-config applies to production only')
    value=render(args.mode,args.origin)
    with args.output.open('x',encoding='utf8',newline='\n') as f:f.write(value)
    print('HTTP profile rendered; existing files were not overwritten')


if __name__=='__main__':main()
